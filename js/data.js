/* --- date ----------------------------------------------------------
   ANNI(fa, mesi): data ISO di "fa" anni e "mesi" mesi fa.
   Usata solo per costruire l'archivio, mai dentro un verdetto. */
function ANNI(fa, mesi) {
  const d = new Date();
  d.setHours(12, 0, 0, 0);
  d.setFullYear(d.getFullYear() - fa);
  d.setMonth(d.getMonth() - (mesi || 0));
  const p = (x) => String(x).padStart(2, "0");
  return d.getFullYear() + "-" + p(d.getMonth() + 1) + "-" + p(d.getDate());
}

